// Bundles hook-src/ into the single dependency-free CommonJS file the plugin runs:
// plugins/tickr/hooks/dist/tickr-hook.cjs (committed; CI rebuilds it and fails on any difference).
//
//   node scripts/build-hook.mjs [--outfile <path>]
import { realpathSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = realpathSync.native(resolve(dirname(fileURLToPath(import.meta.url)), ".."));
const args = process.argv.slice(2);
const at = args.indexOf("--outfile");
const outfile = at >= 0 && args[at + 1] ? resolve(args[at + 1]) : resolve(root, "plugins/tickr/hooks/dist/tickr-hook.cjs");

await build({
  absWorkingDir: root,
  entryPoints: ["hook-src/main.ts"],
  outfile,
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node22",
  charset: "utf8",
  legalComments: "none",
  define: { TICKR_HOOK_BUNDLE: "true" },
  banner: { js: "// Generated by scripts/build-hook.mjs from hook-src/. Do not edit." },
  logLevel: "warning",
});
